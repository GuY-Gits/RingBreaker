"""
RingBreaker SHAP Explainability Engine
======================================
Explains payment risk scores generated by the trained XGBoost Pair Risk Model.
Uses TreeExplainer in margin (log-odds) space with sigmoid probability mapping.
Features automatic fallback to XGBoost's native compiled Tree SHAP engine
(pred_contribs=True) to avoid Windows C-extension / namespace collision issues.

Outputs:
  - Local transaction risk factor breakdowns (risk-increasing vs risk-reducing)
  - Human-readable descriptions for fraud analysts
  - Structured JSON export under data/shap_explanations/
  - Optional SHAP bar plots saved under explain/plots/
  - Global feature importance summary across dataset partitions
"""

